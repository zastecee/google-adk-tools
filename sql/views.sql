--- Customer e Traffic
  SELECT /*+PARALLEL(15)*/
 TRUNC(DC_DATE, 'MM') PP_MONTH,
 BO.GET_WEEK_NUM(DC_DATE) WEEK_NUM,
 BO.GET_SAME_DAY(DC_DATE) SAME_DAY,
 TO_CHAR(DC_DATE, 'DY') WEEK_DAY,
 BO.GET_DATE_MTD(DC_DATE) DATE_MTD,
 D.DC_DATE,
 D.EVENT_DESCRIPTION,
 SUM(D.DC_PREPAD) DC_PREPAD,
 SUM(D.DC_HYBRID) DC_HYBRID,
 SUM(D.DC_TOTAL) DC_TOTAL,
 D.DC_PROVINCE,
 D.DC_SEGMENT,
 NULL,
 TO_CHAR(TRUNC(DC_DATE, 'mm'), 'MM') MMONTH,
 TO_CHAR(TRUNC(DC_DATE, 'dd'), 'DD') DDATE,
 TO_CHAR(TRUNC(DC_DATE, 'yyyy'), 'YYYY') YYEAR
  FROM BO.V_DRA_DAILY_CUSTOMERS_SELECT D
 WHERE DC_DATE >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -5)
   AND DC_DATE < TRUNC(SYSDATE)
 GROUP BY TRUNC(DC_DATE, 'MM'),
          BO.GET_WEEK_NUM(DC_DATE),
          BO.GET_SAME_DAY(DC_DATE),
          TO_CHAR(DC_DATE, 'DY'),
          BO.GET_DATE_MTD(DC_DATE),
          D.DC_DATE,
          D.EVENT_DESCRIPTION,
          D.DC_PROVINCE,
          D.DC_SEGMENT;
          
-- Revenue
SELECT
  /*+PARALLEL(15)*/
  TRUNC(OC_DATE, 'MM') PP_MONTH,  
  BO.GET_WEEK_NUM(OC_DATE) WEEK_NUM,
  BO.GET_SAME_DAY(OC_DATE) SAME_DAY,
  TO_CHAR(OC_DATE, 'DY') WEEK_DAY,
  BO.GET_DATE_MTD(OC_DATE) DATE_MTD,
  OC_DATE,
  SERVICE_NAME,
  DR_PREPAID,
  DR_HYBRID,
  DR_TOTAL,
  NVL(PROVINCE, 'UNKNOWN') PROVINCE,
  BUSINESS_SEGMENT,
  NULL,
  TO_CHAR(TRUNC(OC_DATE, 'mm'), 'MM') MMONTH,
  TO_CHAR(TRUNC(OC_DATE, 'dd'), 'DD') DDATE,
  TO_CHAR(TRUNC(OC_DATE, 'yyyy'), 'YYYY') YYEAR
   FROM BO.V_DRA_DAILY_REVENUE_SELECT_VW D
  WHERE OC_DATE >= ADD_MONTHS(TRUNC(SYSDATE, 'MM'), -5)
    AND OC_DATE < TRUNC(SYSDATE)

