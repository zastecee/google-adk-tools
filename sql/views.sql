SELECT
 /*+PARALLEL(10)*/
 TRUNC(BPM_START_DATE, 'MM') PP_MONTH,
 BO.GET_WEEK_NUM(BPM_START_DATE) WEEK_NUM,
 BO.GET_SAME_DAY(BPM_START_DATE) SAME_DAY,
